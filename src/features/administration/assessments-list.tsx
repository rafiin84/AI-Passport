"use client";
import Link from "next/link";
import { useQuery } from "@tanstack/react-query";
import { adminListAssessments } from "@/lib/api";
import { AdminTable, type Column } from "@/components/admin/admin-table";
import { PageHeader } from "@/components/ui/card";
import { Chip } from "@/components/ui/badge";
import { LoadingBlock } from "@/components/ui/states";
import { Button } from "@/components/ui/button";
import type { Assessment } from "@/types";

type Row = Assessment & { courseTitle: string };

export function AssessmentsList() {
  const { data } = useQuery({ queryKey: ["admin-assessments"], queryFn: adminListAssessments });
  if (!data) return <LoadingBlock />;
  const cols: Column<Row>[] = [
    { key: "c", header: "Course", sortValue: (a) => a.courseTitle, render: (a) => <span className="font-semibold">{a.courseTitle}</span> },
    { key: "q", header: "Questions", render: (a) => `${a.questions.length + a.scenarios.length}${a.practical ? " + practical" : ""}` },
    { key: "g", header: "Generated by", render: (a) => a.generatedBy === "ai" ? "AI (reviewed)" : "Human" },
    { key: "s", header: "Status", sortValue: (a) => a.reviewStatus, render: (a) => <Chip tone={a.reviewStatus === "approved" ? "green" : "saffron"}>{a.reviewStatus.replace("_", " ")}</Chip> },
    { key: "a", header: "", render: (a) => a.courseId ? <Link href={`/admin/courses/${a.courseId}/assessment`} className="font-semibold text-brand underline">Open</Link> : null },
  ];
  return (
    <div className="space-y-6">
      <PageHeader eyebrow="Assessments" title="Verification assessments" sub="Every assessment needs human approval before it can lead to a credential." action={<Button variant="secondary" href="/admin/skills">Skill taxonomy</Button>} />
      <AdminTable columns={cols} rows={data} caption="Assessments" searchText={(a) => a.courseTitle} />
    </div>
  );
}
